// Generate TypeScript
compileFromFile(schemaPath, {
    bannerComment: '/* tslint:disable */\n/**\n* This file was automatically generated by json-schema-to-typescript.\n* DO NOT MODIFY IT BY HAND. Instead, modify the source JSONSchema file,\n* and run update-md-schema.cmd to regenerate this file.\n*/'
}).then(ts => {
    fs.writeFileSync(tsOutputPath, ts);
    console.log(`Successfully generated TypeScript in ${tsOutputPath}`);
}).catch(err => {
    console.error('Failed to generate TypeScript:', err);
    process.exit(1);
});
