const fs = require('fs');
const path = require('path');
// const parseMd = require('json-schema-to-markdown');
const { compileFromFile } = require('json-schema-to-typescript');

const schemaPath = path.join(__dirname, 'sm.ast.schema.json');
const mdOutputPath = path.join(__dirname, 'sm.ast.schema.md');
const tsOutputPath = path.join(__dirname, 'sm.ast.d.ts');

// Generate Markdown
